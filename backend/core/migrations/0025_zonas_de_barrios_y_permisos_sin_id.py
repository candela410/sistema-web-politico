from django.db import migrations

from core.geo import zona_de_poligono


def recalcular_zonas_de_barrios(apps, schema_editor):
    Barrio = apps.get_model("core", "Barrio")
    Zona = apps.get_model("core", "Zona")
    zonas = list(Zona.objects.exclude(geometria=None).values_list("pk", "geometria"))
    for barrio in Barrio.objects.exclude(geometria=None):
        zona = zona_de_poligono(barrio.geometria, zonas) if zonas else None
        if zona != barrio.zona_id:
            barrio.zona_id = zona
            barrio.save(update_fields=["zona"])


